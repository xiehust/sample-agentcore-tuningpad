"""Loopback-only browser fixture, validates requests and records all payloads.
Run: python3 mock_api.py WORK PORT (renders.json generated by framework_contract).
No product server, AWS SDK, K8s, cloud credentials or external I/O.
"""
from copy import deepcopy
from http.server import BaseHTTPRequestHandler, HTTPServer
import json
import math
from pathlib import Path
import sys
from urllib.parse import urlsplit

WORK = Path(sys.argv[1]).resolve()
PORT = int(sys.argv[2])
assert PORT != 8100
PLAN = json.loads((WORK / "renders.json").read_text())[0]["plan"]
NOW = "2026-10-12T12:00:00Z"
PARAMS = {"train_batch_size": 32, "rollout_n": 8, "total_epochs": 1,
          "max_model_len": 4096, "max_prompt_length": 2048, "max_response_length": 4096,
          "kl_loss_coef": 0.001, "rollout_is_threshold": 2, "temperature": 1,
          "val_temperature": 0.6, "val_n": 1, "save_freq": 10, "test_freq": 10,
          "max_actor_ckpt_to_keep": 3}
COMPUTE = {"instance_group": "gpu-p5", "instance_type": "p5.48xlarge", "nodes": 1,
           "provider": "hyperpod", "capacity": "on_demand", "scale_up": True,
           "scale_down_after": True, "max_hours": 6, "budget_usd": None, "max_retries": 2}
STATE = {"preview_fail": 0, "create_fail": 0, "defaults_fail": 0, "last_preview": None,
         "creates": 0, "previews": 0, "violations": []}


def view(run_id, body):
    return {"id": run_id, "name": body.get("name", run_id), "agent_runtime_id": body.get("agent_runtime_id", "rt-gsm"),
            "cluster_id": "cluster-mock", "train_dataset_id": body.get("train_dataset_id", "ds-mock"),
            "val_dataset_id": body.get("val_dataset_id"), "model_id": body.get("model_id", "Qwen/Qwen3.5-2B"),
            "spec": {"plan": deepcopy(PLAN), "params": body.get("params", {}), "val_split": "val",
                     **({"training_mode": body["training_mode"]} if "training_mode" in body else {})},
            "compute": deepcopy(body.get("compute", COMPUTE)), "status": "succeeded", "rayjob_name": None,
            "retries": 0, "started_at": NOW, "ended_at": NOW, "node_hours": 0, "est_cost_usd": 0,
            "progress": {}, "error": None, "created_at": NOW, "job": None,
            "summary": {"last_step": None}, "series": {}, "metric_keys": []}


RUNS = {"legacy": view("legacy", {}), "invalid": view("invalid", {"training_mode": "corrupt-mode"}),
        "invalid-null": view("invalid-null", {"training_mode": None})}
AGENTS = [{"id": f"agent-{key}", "name": name, "template_id": key,
           "runtimes": [{"id": f"rt-{key}", "network_mode": "VPC", "status": "ready",
                         "cluster_id": "cluster-mock", "region": "us-east-1"}]}
          for key, name in (("gsm", "Mock GSM8K"), ("office", "Mock OfficeBench"))]
TEMPLATES = [{"id": key, "label": {"en": key, "zh-CN": key}, "agent_loop": loop,
              "presets": [{"id": "tiny", "label": {"en": "Mock tiny preset", "zh-CN": "模拟小型预设"},
                           "model_id": "Qwen/Qwen3.5-2B", "instance_type": "p5.48xlarge", "nodes": 1,
                           "params": {"train_batch_size": 8, "rollout_n": 4}}]}
             for key, loop in (("gsm", {"max_tokens_per_turn": 1024}), ("office", {"max_tokens_per_turn": 2048}))]


def validate(body, create):
    assert body["training_mode"] in ("sync", "colocate_async"), "invalid mode"
    assert body["agent_runtime_id"] in ("rt-gsm", "rt-office"), "invalid runtime"
    assert body["train_dataset_id"] == "ds-mock", "invalid dataset"
    assert body["name"] and body["model_id"] == "Qwen/Qwen3.5-2B"
    assert isinstance(body["params"], dict)
    assert "training_mode" not in body["params"]
    hours = body["compute"].get("max_hours")
    if body["training_mode"] == "colocate_async":
        assert type(hours) in (float, int) and math.isfinite(hours) and 0 < hours <= 720 and int(hours * 3600) >= 1, "async_deadline_required"
    assert body["compute"]["nodes"] == 1 and body["compute"]["scale_down_after"] is True
    if create:
        assert body.get("confirm_cost") is True, "cost not confirmed"
        preview_body = {k: v for k, v in body.items() if k != "confirm_cost"}
        assert preview_body == STATE["last_preview"], "create differs from last preview"


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *args):
        pass

    def send(self, status, payload, body=None):
        event = {"method": self.command, "path": self.path, "status": status, "body": body}
        with (WORK / "requests.jsonl").open("a") as out:
            out.write(json.dumps(event, ensure_ascii=False) + "\n")
        data = json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        path = urlsplit(self.path).path
        routes = {
            "/api/auth/status": {"auth_required": False, "authenticated": True},
            "/api/agents": AGENTS, "/api/templates": TEMPLATES,
            "/api/clusters": [{"id": "cluster-mock", "name": "Mock cluster", "region": "us-east-1", "status": "ready"}],
            "/api/datasets": [{"id": "ds-mock", "name": "Mock dataset", "status": "ready", "splits": {"train": {"rows": 16}, "val": {"rows": 4}}}],
            "/api/runs/defaults": {"params": PARAMS, "agent_loop": {"max_tokens_per_turn": 1024, "tps_limit": 8, "max_rollout_time": 600}},
            "/api/catalog/instances": {"instances": [{"type": "p5.48xlarge", "ml_type": "ml.p5.48xlarge", "gpus": 8,
                "gpu": "H100", "training": True, "multi_node": True, "price_per_hour": 10, "ec2_price_per_hour": 10, "quota": {"on_demand": 8}}]},
            "/api/runs": list(RUNS.values()), "/__qa": STATE,
        }
        if path == "/api/runs/defaults" and STATE["defaults_fail"]:
            STATE["defaults_fail"] -= 1
            return self.send(503, {"error": {"code": "request.invalid", "message": "injected defaults failure"}})
        if path in routes:
            return self.send(200, routes[path])
        if path.startswith("/api/runs/"):
            pieces = path.split("/")
            if len(pieces) == 4 and pieces[3] in RUNS:
                return self.send(200, RUNS[pieces[3]])
            if pieces[-1] == "pods":
                return self.send(200, [])
        self.send(404, {"error": {"code": "mock.unhandled", "message": path}})

    def do_POST(self):
        body = json.loads(self.rfile.read(int(self.headers.get("Content-Length", "0"))) or b"{}")
        if self.path == "/__qa":
            assert set(body) <= {"preview_fail", "create_fail", "defaults_fail"}
            STATE.update(body)
            return self.send(200, STATE, body)
        create = self.path == "/api/runs"
        if not create and self.path != "/api/runs/preview":
            return self.send(404, {"error": {"code": "mock.unhandled"}}, body)
        try:
            validate(body, create)
        except (AssertionError, KeyError, TypeError) as exc:
            STATE["violations"].append(str(exc))
            return self.send(422, {"error": {"code": "request.invalid", "message": str(exc)}}, body)
        key = "create_fail" if create else "preview_fail"
        if STATE[key]:
            STATE[key] -= 1
            return self.send(503, {"error": {"code": "request.invalid", "message": f"injected {key}"}}, body)
        if create:
            STATE["creates"] += 1
            run_id = f"mock-{STATE['creates']}"
            RUNS[run_id] = view(run_id, body)
            return self.send(200, {"id": run_id, "job_id": "mock-job"}, body)
        STATE["previews"] += 1
        STATE["last_preview"] = deepcopy(body)
        hours = body["compute"]["max_hours"]
        self.send(200, {"training_mode": body["training_mode"], "plan": PLAN, "params": body["params"],
                       "training_plan": None, "model": {"compatible": True},
                       "estimate": {"prepaid": False, "price_per_node_hour": 10, "nodes": 1,
                                    "hourly_usd": 10, "max_hours": hours, "max_cost_usd": hours * 10 if hours else None}}, body)


print(f"MOCK ONLY http://127.0.0.1:{PORT}", flush=True)
HTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
